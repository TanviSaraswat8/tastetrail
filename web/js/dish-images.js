window.dishSlug = n => String(n || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
window.dishImageUrl = (name, w) => {
  const e = window.DISH_IMAGES[window.dishSlug(name)];
  return e ? 'https://commons.wikimedia.org/wiki/Special:FilePath/' + encodeURIComponent(e[0].replace(/ /g, '_')) + '?width=' + (w || 400) : null;
};
window.dishPageUrl = file => 'https://commons.wikimedia.org/wiki/File:' + encodeURIComponent(file.replace(/ /g, '_'));
/* Photo tile for a dish; falls back to the emoji if the photo cannot load (e.g. offline). */
window.dishPic = (item, size, extraClass) => {
  const url = window.dishImageUrl(item.name, size > 100 ? 640 : 320);
  const em = String(item.emoji || '🍽️').replace(/[<>&"]/g, '');
  const box = `width:${size}px;height:${size}px;font-size:${Math.round(size * 0.47)}px`;
  if (!url) return `<span class="emoji-tile ${extraClass || ''}" style="${box}">${em}</span>`;
  return `<span class="emoji-tile dish-photo ${extraClass || ''}" style="${box}" data-emoji="${em}">` +
    `<img src="${url}" alt="" loading="lazy" referrerpolicy="no-referrer" onerror="this.parentNode.classList.remove('dish-photo');this.parentNode.textContent=this.parentNode.dataset.emoji"></span>`;
};
